"""领域同义词扩展：专门补「词面鸿沟」，只作用于 BM25 稀疏路。

要解决的问题（真实案例）：
    员工问「休假怎么申请」，期望命中《考勤与请假管理办法》里的年假申请流程，
    实际 top1 却是《员工手册》里讲法定节假日的那一段泛内容。

原因不是向量模型不行，而是**两边根本不说同一个词**：
    用户说「休假」→ 文档写「请假申请 / 年休假」
    用户说「怎么申请」→ 文档写「提交 / 审批权限 / 直属主管」
词面一个都不重合，BM25 自然零命中；而向量检索在短 query 上又把
「休」这个字面吸到了「调休 / 休息 / 退休」这些不相干的段落上。

为什么只扩稀疏路、不扩向量路：
- 向量路的优势本来就是「语义泛化」，用同义词去改写反而会把它拉回词面匹配，
  丢掉它擅长的近义、跨表述理解；
- BM25 的短板恰恰是「必须字面重合」，补它收益最大、代价最小；
- 两条路在 RRF 融合时互补，比把两边都改成一样的更稳。

维护方式：这张表是给人看的，不是给模型看的。业务上出现新的叫法就往
`GROUPS` 里加一组「用户怎么说 → 文档怎么写」，改完不用重训、不用重建索引。
每一组的「文档怎么写」都应该能在语料（demo-docs/）里找到对应表述——
加了语料里根本没有的词，等于往 BM25 里灌噪声。
扩展词还必须是「同一个意思的另一种说法」，不能是同一篇文档里**兄弟小节**的
标题词：那会把并列的另一个主题顶上来（问住宿费却命中补贴节），
机理见 `expand_for_sparse` 的说明。
"""
from __future__ import annotations

from typing import List, Sequence, Tuple

# 每组 = (触发词, 扩展词)。query 命中任意触发词，就把整组扩展词追加进去。
# 触发词要写得「具体」一点：只写「假」会把「虚假报销、假发票、假条模板」也带上，
# 写成「休假 / 请假 / 年假」才准确。
GROUPS: Sequence[Tuple[Tuple[str, ...], Tuple[str, ...]]] = (
    # 口语「休假」→ 制度里的「请假申请 / 年休假」及审批口径
    (("休假", "请假", "年假", "调休"),
     ("请假申请", "年休假", "审批权限", "直属主管")),
    # 口语「报账」→ 制度里的「费用报销 / 报销单」
    (("报账", "报销", "贴票"),
     ("费用报销", "报销单", "报销流程", "报销时限", "发票要求")),
    # 口语「出差 / 路费」→ 制度里的「出差申请 / 住宿标准」
    # 这里刻意不收「差旅补贴」：它是同一篇文档里 2.3 的标题，属于并列主题而不是
    # 「出差」的另一种说法。用户问住宿费时，它会把补贴节顶到第一，把真正写答案的
    # 2.1 挤出 max_per_doc 配额。（2.2 交通工具是另一个主题，由下一组单独覆盖。）
    # 「住宿费」则必须留：2.1 的正文写的是「住宿费按城市分级据实报销」，
    # 「住宿标准」只是标题、不进 chunk 正文，少了这个词 BM25 就命不中 2.1。
    (("出差", "外出", "路费", "住酒店", "住宿费"),
     ("出差申请", "住宿标准", "住宿费", "费用标准")),
    # 口语「坐飞机 / 打车」→ 03 的 §2.2 正文：「高铁/动车：二等座」「飞机：经济舱」
    # 扩展词全部取自 §2.2 的**正文**，一个不漏地核过：
    #   「交通工具」是这一节的标题、不进 chunk 正文，写进来等于零命中——别加；
    #   「市内交通」在 §2.2 和 §2.3 各出现一次，会把差旅补贴那节一起拉上来——别加。
    # 触发词里「机票 / 出租车 / 路费」在语料里 0 次，只作为用户口语存在，不影响索引。
    (("坐飞机", "飞机", "机票", "高铁", "动车", "打车", "出租车", "路费",
      "二等座", "经济舱"),
     ("二等座", "经济舱", "高铁", "动车", "飞机")),
    # 口语「打卡 / 扣钱」→ 制度里的「考勤管理 / 补卡申请」
    (("打卡", "迟到", "忘记打卡", "考勤", "扣钱"),
     ("考勤管理", "打卡要求", "补卡申请", "漏打卡", "扣减绩效")),
    # 口语「登录不上 / 忘了密码」→ 规范里的「密码策略 / 多因素认证」
    (("密码", "账号", "登录", "验证码", "U盘", "U 盘"),
     ("密码策略", "多因素认证", "账号共享", "终端安全", "外部设备")),
    # 口语「新人 / 转正」→ 指引里的「新员工入职 / 转正申请书」
    (("入职", "新人", "试用期", "转正", "报到"),
     ("新员工入职", "入职培训", "转正申请书", "必修课程", "试用期考核")),
    # 口语「钱什么时候到账」→ 制度里写的是「随工资打款」。
    # 「到账」在全语料出现 0 次，只有 03 的 §3.2 写「审批通过后于次月 15 日
    # 随工资打款」，问「报销多久能到账」时字面零命中，答案里最关键的那个
    # 数字就捞不回来。
    # 这组必须独立成组、不能并进「报销」组：并进去会让每条报销问题都被
    # 「打款」拉到 §3.2，反过来把发票要求那节挤掉（报销组已有 5 个扩展词，
    # 再加就是对 §3.2 的过度加权）。
    # 触发词不收「什么时候发」——它会把「工资什么时候发」也拽到 §3.2，
    # 而那个问题的答案在员工手册的「发薪日」，属于跨主题串扰。
    (("到账", "打款", "发钱"),
     ("打款",)),
)

# 触发词按长度倒序匹配，避免「忘记打卡」被更短的「打卡」抢先切走
_FLAT = sorted(((t, g[1]) for g in GROUPS for t in g[0]),
               key=lambda x: -len(x[0]))


def expand_terms(query: str) -> List[str]:
    """返回命中的扩展词（去重、保序、不含原 query 里已有的词）。"""
    q = (query or "").strip()
    if not q:
        return []
    out: List[str] = []
    seen = set()
    hit_groups = set()
    for trigger, words in _FLAT:
        if trigger not in q:
            continue
        key = words[0] if words else trigger
        if key in hit_groups:      # 同组只扩一次
            continue
        hit_groups.add(key)
        for w in words:
            if w and w not in q and w not in seen:
                seen.add(w)
                out.append(w)
    return out


def expand_for_sparse(query: str, max_terms: int = 12) -> str:
    """拼给 BM25 用的长 query。

    BM25 的得分是「命中词贡献之和」，追加词本身不扣分——但**不扣分不等于挤不掉**。
    融合用的是 RRF，比的是**排名**而不是分数：扩展词把某条 chunk 的 BM25 名次
    往前推一位，别的 chunk 就往后掉一位，`1/(k+rank)` 直接掉一档，两路一加照样
    被反超。「分数不降」和「排名不变」是两件独立的事。

    所以真正的约束是：扩展词只能补「同一个意思的不同说法」，不能补「同一篇文档里
    的其他主题」。后者会把兄弟小节顶上来——问「出差住宿费」却把「差旅补贴」那一节
    排到第一，再用 `max_per_doc` 一限流，写着答案的小节连候选都进不去，是净损失。
    """
    q = (query or "").strip()
    terms = expand_terms(q)[:max_terms]
    if not terms:
        return q
    return f"{q} " + " ".join(terms)


def describe(query: str) -> str:
    """调试用：说明这条 query 会被扩成什么。"""
    terms = expand_terms(query)
    return f"{query} → {terms}" if terms else f"{query} → （无扩展）"
